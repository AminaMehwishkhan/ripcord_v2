"""
make_report.py — write docs/evaluation.md from benchmark/results/benchmark_results.json.

Every number in the report is copied from the results file, which evaluate.py computed on the
held-out test split. Nothing is typed by hand; re-run this after re-running evaluate.py.

    python make_report.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "benchmark" / "results" / "benchmark_results.json"
OUT = ROOT / "docs" / "evaluation.md"

ORDER = ["no_check", "always_confirm", "asr_mean_conf", "asr_min_conf", "ripcord_v1_rules", "ripcord_v2"]


def pct(x, d=1):
    return "—" if x is None else f"{x * 100:.{d}f}%"


def rate(r, d=1):
    return "—" if not r else f"{pct(r['value'], d)} ({pct(r['ci'][0], d)}–{pct(r['ci'][1], d)})"


def main() -> None:
    if not RESULTS.exists():
        sys.exit("Run benchmark/evaluate.py first.")
    r = json.loads(RESULTS.read_text())
    p = r["policies"]
    v2, base = p.get("ripcord_v2"), p["no_check"]
    meta = r["model"]["meta"]
    ds = r["dataset"]

    L: list[str] = []
    a = L.append
    a("# Evaluation\n")
    a("> This file is generated by `benchmark/make_report.py` from `benchmark/results/benchmark_results.json`. "
      "Do not edit the numbers by hand.\n")
    a("## What was measured\n")
    a(f"**{r['n_calls']} test calls** the system had never seen: the voices and the order numbers are different from the "
      f"training and validation data (splits are made by speaker and by number). Each call is one caller saying a 4-digit "
      f"order number, run through the real pipeline (`entity_detector` → risk engine → `SessionOrchestrator`). If a policy "
      f"asks a question, the caller's recorded reply (\"yes, that's right\" or \"no, it's …\", also run through the "
      f"recogniser) is played back, so the final result includes the recovery.\n")
    a(f"On this data the recogniser alone hears **{pct(r['capture_error_rate'])}** of the numbers wrong "
      f"(and finds no number at all in {pct(r['no_entity_rate'])} of calls). That is a harsh setting on purpose: it gives "
      f"the safety layer something to do. A premium recogniser would make fewer errors, so read the *comparison between "
      f"systems*, not the absolute rates.\n")
    a("## Results on the held-out test set\n")
    a("| System | Wrong number acted on | Resolved correctly | Left unresolved* | Mishearings caught | Needless questions | Questions per call |")
    a("|---|---|---|---|---|---|---|")
    for k in ORDER:
        if k in p:
            x = p[k]
            a(f"| {x['label']} | {rate(x['wrong_action'])} | {pct(x['correct_action']['value'], 0)} | "
              f"{pct(x['unresolved']['value'], 0)} | {rate(x['error_catch_rate'], 0)} | "
              f"{rate(x['false_alarm_rate'], 0)} | {x['questions_per_call']['value']:.2f} |")
    a("\nIntervals in brackets are 95% bootstrap confidence intervals over the test calls. "
      "\"Wrong number acted on\" counts every call that ended with the wrong order number being used; "
      "\"needless questions\" counts calls where the number was heard correctly but the system asked anyway.\n")
    a("\\* *Unresolved* means the call was still waiting after the one recorded caller reply: the reply was misheard too, "
      "or no number was found. In a live call the agent would ask again or hand over to a person, so these are "
      "safe, not wrong. They are high because the benchmark replays only one reply per call.\n")

    a("## What the numbers say\n")
    if v2:
        a(f"- **The plain agent acts on a wrong number {pct(base['wrong_action']['value'], 0)} of the time** with this "
          f"recogniser. Ripcord v2 brings that to **{pct(v2['wrong_action']['value'], 1)}** "
          f"(95% CI {pct(v2['wrong_action']['ci'][0], 1)}–{pct(v2['wrong_action']['ci'][1], 1)}), "
          f"and it resolves {pct(v2['correct_action']['value'], 0)} of calls correctly "
          f"(plain agent: {pct(base['correct_action']['value'], 0)}).")
        overlap = [p[k]["label"] for k in ("asr_mean_conf", "asr_min_conf", "ripcord_v1_rules") if k in p and
                   not (p[k]["wrong_action"]["ci"][1] < v2["wrong_action"]["ci"][0]
                        or p[k]["wrong_action"]["ci"][0] > v2["wrong_action"]["ci"][1])]
        if overlap:
            a("- **On wrong actions, v2 cannot be told apart from " + ", ".join(overlap) + "** (confidence intervals overlap). "
              "Almost all of the gain comes from one simple fact: most of this recogniser's mistakes drop or garble "
              "digits, so the capture is not 4 digits long, and every system that checks the digit count and asks a "
              "question catches them. The learned scorer is not what makes the difference here.")
        v1 = p.get("ripcord_v1_rules")
        if v1 and v1["false_alarm_rate"] and v2["false_alarm_rate"]:
            a(f"- **v2 versus v1 (hand-tuned rules):** similar safety, but v2 asks needless questions on "
              f"{pct(v2['false_alarm_rate']['value'], 0)} of correctly heard calls against v1's "
              f"{pct(v1['false_alarm_rate']['value'], 0)}.")
    ac = p.get("always_confirm")
    if ac:
        a(f"- **Always reading back never acts on a wrong number ({pct(ac['wrong_action']['value'], 1)}), but it is the most "
          f"annoying:** {ac['questions_per_call']['value']:.2f} questions per call, and only "
          f"{pct(ac['correct_action']['value'], 0)} of calls finish correctly in one round.\n")

    if v2:
        a("### The hard case: a wrong number that looks normal\n")
        a("A wrong length (\"one five zero\") is easy to spot. The dangerous mistakes are wrong numbers that still look "
          "like a normal 4-digit order number. **The test set has only "
          f"{v2.get('misheard_valid_format_calls', '—')} of them**, so nothing about this case can be concluded from the "
          "test set alone. At the chosen operating point:\n")
        a("| System | Valid-looking wrong numbers caught |")
        a("|---|---|")
        for k in ORDER:
            if k in p and k not in ("no_check", "always_confirm"):
                a(f"| {p[k]['label']} | {rate(p[k].get('silent_catch_rate'), 0)} |")
        hc = r.get("hard_case")
        if hc:
            a(f"\nA larger sample: on the **{hc['n']} well-formed captures in train+validation "
              f"({hc['n_misheard']} of them misheard)**, using cross-validated predictions for the learned model, "
              "the ranking quality (AUROC, 0.5 = coin flip) is:\n")
            a("| Score | AUROC, well-formed captures only |")
            a("|---|---|")
            for k in ("ripcord_v2", "asr_mean_conf", "asr_min_conf"):
                a(f"| {p[k]['label']} | {hc['auroc'][k]} |")
            a("\nSo for this recogniser, its own confidence scores say almost nothing about whether a well-formed number "
              "is right. How the number was *said* (as one big number, in pairs) and how fast says more. "
              "On the test set's 7 cases the same pattern shows "
              f"(v2 {r['auroc_valid_format'].get('ripcord_v2')}, ASR confidence {r['auroc_valid_format'].get('asr_mean_conf')}), "
              "but with 7 positives that is only a hint.\n")
            a("This is also why the model is retrained per recogniser: a recogniser whose confidence is informative "
              "would weight it more.\n")

    a("### Ranking quality and calibration\n")
    a("| Score | AUROC (all captures) |")
    a("|---|---|")
    for k, v in r["auroc"].items():
        a(f"| {p[k]['label']} | {v} |")
    if r.get("reliability"):
        a(f"\nCalibration of the learned model: expected calibration error **{r['reliability']['ece']}** "
          "(0 = its probabilities match how often it is really wrong).\n")

    a("## By audio condition\n")
    a("| Condition | Calls | Wrong number: plain agent | Wrong number: with Ripcord | Asked a question |")
    a("|---|---|---|---|---|")
    for c in r["by_condition"].values():
        nc, rv = c.get("no_check", {}), c.get("ripcord_v2", {})
        a(f"| {c['label']} | {c['n']} | {pct(nc.get('wrong_action'), 0)} | {pct(rv.get('wrong_action'), 0)} | {pct(rv.get('asked'), 0)} |")
    a("\nPer-condition cells are small; look at the pattern, not the exact values.\n")

    a("## Where Ripcord fails\n")
    sf = r.get("silent_failures", [])
    if v2:
        n_wrong = round(v2["wrong_action"]["value"] * v2["wrong_action"]["n"])
        a(f"With Ripcord, **{n_wrong} of {v2['wrong_action']['n']} calls** ({pct(v2['wrong_action']['value'])}) still ended on a wrong "
          "number. Each is a wrong number that looked like a normal 4-digit order number. Heard / actually said / "
          "weakest-word confidence:\n")
        for s_ in sf[:10]:
            mc = f"{s_['min_conf']:.2f}" if s_.get("min_conf") is not None else "n/a"
            a(f"- {s_['condition']}: heard **{s_['heard']}**, caller said **{s_['truth']}**, weakest word {mc} — "
              f"\"{s_['transcript']}\"")
        big = {"thousand", "hundred", "ten", "eleven", "twelve", "thirteen", "fourteen", "fifteen", "sixteen",
               "seventeen", "eighteen", "nineteen", "twenty", "thirty", "forty", "fifty", "sixty", "seventy",
               "eighty", "ninety"}
        n_big = sum(1 for s_ in sf if big & set(s_["transcript"].split()))
        confs = [s_["min_conf"] for s_ in sf if s_.get("min_conf") is not None]
        if sf:
            a(f"\n{n_big} of the {len(sf)} listed were said as \"… thousand … hundred …\" or in pairs (\"eighteen nineteen\"), "
              "where the recogniser merges or swaps words and still produces four digits. "
              + (f"Their weakest-word confidence ran from {min(confs):.2f} to {max(confs):.2f}, so the recogniser's own "
                 "score was not a reliable warning. " if confs else "")
              + "The caller's own corrections and a read-back of every number are the other defences.\n")

    a("## How the model was trained\n")
    a(f"- A logistic regression over {len(r['model']['features'])} explainable features of how the number was heard "
      "(confidence of the number words, spoken style, homophone digits, speaking rate and so on). Weight signs are "
      "constrained to common sense (more confidence never raises risk) so the explanations in the dashboard are trustworthy.")
    a("- It is fitted on **well-formed captures only** (the hard case). A wrong digit count is handled by a rate "
      f"measured on the training data ({pct(r['model'].get('invalid_format_p'), 1) if r['model'].get('invalid_format_p') else 'n/a'} "
      "of such captures were wrong), because those are almost always wrong and are easy to see.")
    a(f"- Trained on the train + validation splits only ({meta.get('n_examples')} examples; "
      f"{meta.get('n_wellformed_examples')} well-formed, {meta.get('n_wellformed_misheard')} of them misheard). "
      "5-fold cross-validation chose the regularisation: the strongest setting within one standard error of the best "
      f"(λ = {meta.get('lambda')}, shrunk toward a prior that lower confidence means more risk, which only matters "
      f"because there are so few misheard examples). The question threshold ({r['model']['threshold']}) also comes from "
      "cross-validation. The test split was scored only after all of that was fixed.")
    a(f"- The threshold comes from a cost model: acting on a wrong number costs {meta.get('cost_ratio'):g}× "
      "as much as asking one question. Raise `--cost-ratio` in `train_risk_model.py` for higher-stakes workflows.")
    a("- The threshold baselines are tuned with the same cost model on the same well-formed captures, and they also get "
      "the digit-count check for free, so the comparison is not a straw man.\n")
    a("### What changed after the first test run\n")
    a("The first time the test split was scored it exposed a bug in the session logic: if the first capture had the "
      "wrong number of digits and the caller's reply was garbled, repeating the same malformed number could be "
      "\"confirmed\". It is fixed (a malformed number can never be verified, enforced in the orchestrator and again in "
      "the action layer, with regression tests) and the test split was scored again with the **same trained model**. "
      "No model weight, threshold or selection rule was changed after looking at test results.\n")

    a("## Data\n")
    a(f"- {ds['total']} generated calls ({ds['per_split']['train']} train / {ds['per_split']['val']} val / "
      f"{ds['per_split']['test']} test), {ds['speakers']} speakers.")
    a(f"- Speech: {ds['tts']}. Recogniser: {ds['asr']}. Conditions: clean, five noise levels, phone-line band-limiting, "
      "echo, and fast speech.")
    a("- Each call includes the caller's recorded \"yes\" and \"no, it's …\" replies.\n")

    a("## Honest limits\n")
    a("- **The voices are synthetic** (text-to-speech), not real callers. Real people hesitate, interrupt and "
      "mumble in ways TTS does not.")
    a("- **The recogniser is an open-source model**, not AssemblyAI. Its confidence scores behave differently, so "
      "the trained weights and the threshold should be re-fit on your own recogniser's output before you trust "
      "absolute numbers. The pipeline, tests and training script are built so that is a one-command job "
      "(`benchmark/README.md`).")
    a("- **One entity type** (a 4-digit order number) in one simulated workflow.")
    a("- **Replies are recorded once per call.** If the restated number is misheard again, the system asks again; "
      "the benchmark only plays one reply, so those calls count as unresolved rather than being walked through "
      "every retry. This overstates the unresolved rate for every system.")
    a("- **Tests of the caller correcting a number already accepted** (the second chance for a confident-but-wrong "
      "capture) are in the unit tests and the dashboard, not in these numbers: each call here is a single utterance.")
    a("- The 10 hand-written scenarios in `demo/scenarios.json` are illustrations for the dashboard and are "
      "not part of these numbers.\n")

    a("## Reproduce\n")
    a("```bash\ncd benchmark\n"
      "python build_dataset.py --n 900 --shard 0 --nshards 2 &   # synthetic speech -> recogniser -> data/*.jsonl\n"
      "python build_dataset.py --n 900 --shard 1 --nshards 2\n"
      "python train_risk_model.py                  # train + val only\n"
      "python evaluate.py                          # test split, once\n"
      "python make_report.py                       # regenerate this file\n```\n")

    OUT.write_text("\n".join(L), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
